#!/usr/bin/env python3
"""Emit the debugfs manifest for every user-space change this project makes.

The committee's answer to "may we change the rootfs?" was 「改动的话得提供对应的
debugfs 信息，我们需要评估改动的影响」 -- changes are allowed but must be auditable.
This produces that audit, in the form they asked for: a debugfs script plus a
per-file record with sizes and digests.

Scope of the change set, deliberately minimal:

  * three NEW files -- the committee's own test pages, which are NOT in the
    delivered image (it ships only a 3,024 B placeholder at
    /usr/share/kiosk/index.html);
  * one 44-byte CONFIGURATION file rewritten -- /etc/kiosk/url, so the vendor's own
    session script points at the committee page.

Nothing else is touched: no binary, no /init, no /etc/inittab, no library.  That is
what makes the change reviewable, and it is why the manifest is short.

Usage:
    python host/make_rootfs_manifest.py            # write rootfs/rootfs-change-manifest.dbg
    python host/make_rootfs_manifest.py --check    # verify the source files only
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

# (guest path, source path relative to the package root, delivered-in-image?)
CHANGES = [
    ("/usr/share/kiosk/official/index.html", "pages/index.html", False),
    ("/usr/share/kiosk/official/interaction.html", "pages/interaction.html", False),
    ("/usr/share/kiosk/official/layout.html", "pages/layout.html", False),
    ("/etc/kiosk/url", None, True),
]

# The three pages also exist as the committee's read-only originals one level above
# this package (`../备份文件/`).  Prefer those when present; `pages/` is a byte-for-byte
# copy of them (the digests below match either way), so the package alone suffices.
ORIGINAL_DIR = "../备份文件"
FALLBACK_DIR = "pages"

# The url file's content after the change; it is 35 bytes in the image because it
# holds the placeholder path.
NEW_URL = "file:///usr/share/kiosk/official/index.html\n"

HEADER = """# rootfs change manifest -- debugfs form
#
# Generated by host/make_rootfs_manifest.py.  Every write this project makes to
# the guest filesystem is listed here, with the command that reproduces it.
#
# Apply against a WORKING COPY of the delivered image, never the original:
#   python host/rootfs_audit.py workcopy
#   debugfs -w -f <this-file> <working-copy.img>
#
# Scope: three new files (the committee's test pages, absent from the image) and
# one rewritten configuration file.  No binary, no /init, no /etc/inittab.

"""


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def debugfs_write(guest_path: str, staged_name: str) -> str:
    """A debugfs `write` command, using a path relative to the staging directory.

    Relative on purpose: an absolute Windows path would make the script unusable on
    the machine that actually runs debugfs (the committee's, and this project's WSL
    build host).  The staging directory holds every file under a plain name, so the
    script runs from there regardless of platform.
    """
    return f"write {staged_name} {guest_path}"


def main(argv: list[str]) -> int:
    ws = pathlib.Path(__file__).resolve().parent.parent
    check_only = "--check" in argv
    stage = ws / "rootfs" / "debugfs-stage"

    lines = [HEADER]
    lines.append("# Run from the staging directory, which holds every file:")
    lines.append("#   cd rootfs/debugfs-stage")
    lines.append("#   debugfs -w -f ../rootfs-change-manifest.dbg <working-copy.img>")
    lines.append("")
    lines.append("# --- files written into the guest ---")

    records = []
    for guest, src, present in CHANGES:
        if src is None:
            staged = stage / "kiosk-url"
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_text(NEW_URL, encoding="utf-8", newline="\n")
            note = "REWRITTEN (was the 3,024 B placeholder path)"
        else:
            original = ws / src
            if not original.is_file():
                fallback = ws / FALLBACK_DIR / original.name
                if fallback.is_file():
                    original = fallback
            if not original.is_file():
                raise SystemExit(
                    f"source not found: {ws / src}\n"
                    f"  (also tried {ws / FALLBACK_DIR / (ws / src).name})"
                )
            staged = stage / original.name
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_bytes(original.read_bytes())
            note = "PRESENT in image" if present else "NEW FILE (absent from image)"
        lines.append(f"# {guest}  <-  {staged.name}  [{note}]")
        lines.append(debugfs_write(guest, staged.name))
        records.append((guest, staged, note))

    lines.append("")
    lines.append("# --- verification: compare the image against these digests ---")
    for guest, host, _ in records:
        lines.append(f"# {guest}  bytes={host.stat().st_size}  sha256={sha256(host)}")

    lines.append("")
    lines.append("# --- nothing else is modified ---")
    for untouched in (
        "/usr/local/bin/x11-session",
        "/etc/inittab",
        "/etc/init.d/kiosk-boot",
        "/usr/lib/chromium/chromium",
        "/usr/libexec/Xorg",
        "/usr/bin/jwm",
        "/etc/chromium/chromium.conf",
    ):
        lines.append(f"# unchanged: {untouched}")

    text = "\n".join(lines) + "\n"

    print("rootfs change manifest")
    print(f"  files written : {len(records)}")
    for guest, host, note in records:
        print(f"    {guest:42s} {host.stat().st_size:6d} B  {note}")
    print(f"  debugfs verbs : {sum(1 for l in lines if l.startswith('write '))}")

    if check_only:
        print("  --check: not writing the manifest")
        return 0

    out = ws / "rootfs" / "rootfs-change-manifest.dbg"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"  wrote {out.relative_to(ws)} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
